package scoreboard

// 2x3 bitmap font metrics - smaller than 3x5
const (
	fontW2x3    = 2 // glyph pixel width
	fontH2x3    = 3 // glyph pixel height
	fontAdv2x3  = 3 // advance per character (fontW + 1px gap)
	fontRowH2x3 = 4 // row advance (fontH + 1px gap)
)

